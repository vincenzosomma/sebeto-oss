export const CATALOG: Record<Locale, Record<MessageKey, string>> = { en, it };
export const LOCALES: readonly Locale[] = ['en', 'it'];

/** Pure: look up a key and fill `{name}` placeholders. Falls back to English, then to the key. */
export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = CATALOG[locale][key] ?? CATALOG.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Pure: pick a supported locale from a BCP-47 tag like "it-IT". */
export function detectLocale(tag: string | undefined | null): Locale {
  const base = (tag ?? '').toLowerCase().split('-')[0];
  return base === 'it' ? 'it' : 'en';
}
